/**
 * Federation pull (spec: community registries PULL from the canonical
 * listing). Fetches the official federation snapshot and materializes:
 *
 *   docs/public/registry/listings.json   machine-readable index
 *   docs/registry/listings.md            human page (static table)
 *
 * Runs at build time so the site always mirrors the canonical registry
 * without holding any write access to it.
 */

import { writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const url = process.env['FEDERATION_URL'] ?? 'https://listing.reposell.dev/federation/v1/snapshot.json';

// Tags to filter by — only pull listings with at least one matching tag.
// Set REPOSELL_TAGS env var to override (comma-separated), or use defaults.
const defaultTags = ['reposell', 'example'];
const filterTags = (process.env['REPOSELL_TAGS'] ?? '').split(',').map((t) => t.trim()).filter(Boolean);
const tags = filterTags.length > 0 ? filterTags : defaultTags;

let listings = [];
try {
  const res = await fetch(url, { headers: { accept: 'application/json' } });
  if (!res.ok) throw new Error(`HTTP ${res.status}`);
  const snap = await res.json();
  const allEntries = (snap.listings ?? []).map((entry) => ({
    id: entry.id,
    repository: entry.product?.repository ?? '(unknown)',
    release: entry.product?.release ?? '(unknown)',
    description: entry.product?.description ?? '',
    sell_url: entry.seller?.sell_url ?? '',
    payment_link: entry.seller?.payment_link ?? '',
    amount: entry.listing?.discovery_price?.amount ?? null,
    currency: entry.listing?.discovery_price?.currency ?? '',
    repo_price: entry.product?.price ?? null,
    repo_currency: entry.product?.currency ?? '',
    license: entry.product?.license ?? '',
    tags: entry.tags ?? [],
    community: entry.community ?? null,
    readme: entry.readme ?? null,
  }));
  // Filter by tags — include if listing has at least one matching tag.
  // If a listing has no tags and we're using defaults (no custom REPOSELL_TAGS),
  // include it so source data without tags is not silently dropped.
  listings = allEntries.filter((entry) => {
    if (tags.length === 0) return true; // no filter = include all
    if (entry.tags.length === 0 && filterTags.length === 0) return true;
    return entry.tags.some((t) => tags.includes(t));
  });
  console.log(`tag filter [${tags.join(', ')}]: ${allEntries.length} total → ${listings.length} matching`);
} catch (error) {
  console.warn(`federation pull failed (${error instanceof Error ? error.message : String(error)}) — empty index`);
}

const outDir = path.join(root, 'docs', 'public', 'registry');
await mkdir(outDir, { recursive: true });
await writeFile(
  path.join(outDir, 'listings.json'),
  `${JSON.stringify({ updated: new Date().toISOString(), source: url, listings }, null, 2)}\n`,
);

const OFFICIAL_BASE = 'https://listing.reposell.dev';

const rows = listings
  .map(
    (entry) => {
      const slug = entry.repository.replace('/', '-').toLowerCase();
      const detailUrl = `${OFFICIAL_BASE}/registry/tools/${slug}/`;
      const discussion = entry.community?.github?.discussion_url
        ? `[Discussion ↗](${entry.community.github.discussion_url})`
        : '—';
      return `| \`${entry.repository}\` | ${entry.release} | ${entry.amount !== null ? `\`${entry.amount} ${entry.currency}\`` : '—'} | [View details](${detailUrl}) | ${discussion} |`;
    },
  )
  .join('\n');

const md = `<!-- GENERATED by scripts/pull-federation.mjs — do not edit by hand. -->
# Connected Listings

Federated from the canonical reposell registry (\`${url}\`). Last sync:
${new Date().toISOString()}

${listings.length === 0 ? '> No tools are listed yet.' : `| Repository | Release | Discovery | Details | Community |\n| --- | --- | --- | --- | --- |\n${rows}`}

Every entry is verified against the seller's live \`/sell\` endpoint before
it appears here. Visit the [official listing](${OFFICIAL_BASE}/registry/listings)
for the full discovery and purchase flow. Run your site build to re-sync the
federated index.
`;
await mkdir(path.dirname(path.join(root, 'docs', 'registry', 'listings.md')), { recursive: true });
await writeFile(path.join(root, 'docs', 'registry', 'listings.md'), md);

console.log(`federation pull: ${listings.length} listing(s) → docs/public/registry/listings.json`);
